def get_digest_creation_prompt(articles: list) -> str:
    """
    Generate prompt for creating digest from articles

    Args:
        articles: List of article dictionaries

    Returns:
        User prompt string
    """
    articles_text = "\n\n".join([
        f"Статья {i + 1}:\n"
        f"Заголовок: {article['title']}\n"
        f"Содержание: {article['content'][:800]}..."
        for i, article in enumerate(articles)
    ])

    return f"""Создай выжимку из этих {len(articles)} статей про образование за рубежом:

{articles_text}

Напомню требования:
- ОДНО короткое предложение на каждую статью - только самая главная информация
- Используй эмодзи
- Максимально кратко и лаконично
- НЕ добавляй призывы к действию в конце
- Только суть!

Создай выжимку:"""


